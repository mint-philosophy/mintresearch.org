import type { TrackData } from '../../systems/AudioEngine';

function makeTrack(bpm: number, lead: number[], bass: number[]): TrackData {
  return {
    bpm,
    loop: true,
    notes: [
      lead.map((freq) => ({
        freq,
        duration: 0.5,
        volume: freq === 0 ? 0 : 0.5,
      })),
      bass.map((freq) => ({
        freq,
        duration: 2,
        type: 'triangle',
        volume: freq === 0 ? 0 : 0.28,
      })),
    ],
  };
}

